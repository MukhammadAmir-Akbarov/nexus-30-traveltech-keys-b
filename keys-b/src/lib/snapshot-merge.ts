import type { CorpusItem, Guide } from './types.ts';

/**
 * Слияние посева из исходников со снимком на диске.
 *
 * Вынесено из store.ts в чистый модуль по двум причинам. Во-первых, это
 * единственное место, где решается, ЧТО переживает рестарт, — и оно обязано
 * быть под самопроверкой. Во-вторых, store.ts импортирует данные через
 * алиас `@/`, которого нет у node вне сборки, поэтому npm run check не может
 * проверить store.ts напрямую — а этот модуль может.
 *
 * История: снимок целиком ЗАМЕНЯЛ посев (`fresh.corpus = saved.corpus`).
 * Абзац, добавленный в corpus.ts, не доезжал до поиска ни на одном инстансе
 * со старым снимком, а /how честно показывал новое число — он читает
 * константу сборки, не стор. Ровно та сигнатура, что наблюдалась на проде:
 * «поиск не находит то, что в исходниках есть, счётчики сходятся».
 */

/**
 * Корпус: исходник — канон. Из снимка доживает только добавленное
 * администратором (id вне исходника). Факт исходника, удалённый через
 * админку, после рестарта воскресает — для демо это правильная сторона
 * компромисса: код всегда сильнее случайного клика.
 */
export function mergeCorpus(source: CorpusItem[], saved: CorpusItem[] | undefined): CorpusItem[] {
  if (!saved?.length) return source;
  const sourceIds = new Set(source.map((item) => item.id));
  return [...source, ...saved.filter((item) => !sourceIds.has(item.id))];
}

/**
 * Гиды: канон обратный. Сохранённый гид заменяет посевного с тем же id —
 * на нём живёт изменяемое состояние (verified переключает администратор,
 * терять это при рестарте нельзя). Но новые гиды из исходника обязаны
 * появиться: раньше и они молча пропадали под старым снимком.
 */
export function mergeGuides(source: Guide[], saved: Guide[] | undefined): Guide[] {
  if (!saved?.length) return source;
  const savedIds = new Set(saved.map((guide) => guide.id));
  return [...saved, ...source.filter((guide) => !savedIds.has(guide.id))];
}

/**
 * Появление страницы при переходе.
 *
 * ПОЧЕМУ НЕ framer-motion. Здесь стоял `<motion.div initial={{opacity: 0}}>`.
 * Framer Motion выставляет это начальное состояние ИНЛАЙНОВЫМ стилем ещё на
 * сервере, а снимает его только клиентский JS. То есть сервер отрисовывал
 * страницу и тут же её прятал.
 *
 * Измерено: `curl` отдаёт 11 КБ содержимого внутри <main>, а страница,
 * открытая с выключенным JS, показывает пустоту — видны только шапка и нижняя
 * панель, потому что они живут в layout, снаружи этого файла. То же самое
 * увидит зал, если на площадке отвалится сеть или упадёт любой скрипт:
 * текст будет в DOM, но невидимый.
 *
 * CSS-анимация такого свойства не имеет: она проигрывается самим движком
 * рендеринга, без JS. Класс `.appear` уже есть в globals.css и уже учтён в
 * блоке prefers-reduced-motion — там длительность схлопывается до 0.01ms,
 * и содержимое просто появляется сразу.
 *
 * Заодно из каждой страницы уходит клиентский компонент: этому файлу больше
 * не нужна директива 'use client'.
 */
export default function Template({ children }: { children: React.ReactNode }) {
  return <div className="appear">{children}</div>;
}
